"""
Gemini API integration module for CampusAI.
Handles communication with Google Gemini Generative AI using the official google-genai SDK.
"""

from typing import Any, Dict, List, Optional
from google import genai
from google.genai import types
from google.genai.errors import APIError

try:
    from config import DEFAULT_MODEL_NAME, SYSTEM_INSTRUCTION
except ImportError:
    from campusai.config import DEFAULT_MODEL_NAME, SYSTEM_INSTRUCTION


class GeminiServiceError(Exception):
    """Custom exception class for Gemini Service errors."""
    pass


def get_gemini_client(api_key: Optional[str]) -> genai.Client:
    """
    Initializes and returns a Google GenAI Client.

    Raises:
        GeminiServiceError: If the API key is missing or empty.
    """
    if not api_key or not api_key.strip():
        raise GeminiServiceError(
            "Gemini API key is missing. Please configure your GEMINI_API_KEY "
            "in a .env file or Streamlit secrets."
        )
    return genai.Client(api_key=api_key.strip())


def format_chat_history(messages: List[Dict[str, str]]) -> List[types.Content]:
    """
    Converts Streamlit session messages into google-genai Content types.
    Only includes completed conversation turns with non-empty text.
    """
    formatted_contents: List[types.Content] = []
    for msg in messages:
        role = msg.get("role", "")
        content = msg.get("content", "").strip()
        if not content:
            continue

        # In google-genai, roles are 'user' and 'model'
        gemini_role = "user" if role == "user" else "model"
        formatted_contents.append(
            types.Content(
                role=gemini_role,
                parts=[types.Part.from_text(text=content)]
            )
        )
    return formatted_contents


def generate_response(
    api_key: Optional[str],
    user_message: str,
    chat_history: Optional[List[Dict[str, str]]] = None,
    model_name: str = DEFAULT_MODEL_NAME,
    system_instruction: str = SYSTEM_INSTRUCTION,
) -> str:
    """
    Sends the user message and conversation history to Gemini and returns the response.

    Args:
        api_key: Google Gemini API key.
        user_message: The message input by the student.
        chat_history: List of past message dicts [{'role': 'user'|'assistant', 'content': '...'}]
        model_name: The Gemini model identifier to call.
        system_instruction: System prompt to govern chatbot persona and guidelines.

    Returns:
        The text response generated by Gemini.

    Raises:
        GeminiServiceError: If input is invalid, API key is missing, or the API call fails.
    """
    if not user_message or not user_message.strip():
        raise GeminiServiceError("Message cannot be empty.")

    client = get_gemini_client(api_key)

    # Prepare chat history contents
    contents: List[types.Content] = []
    if chat_history:
        contents.extend(format_chat_history(chat_history))

    # Append current user prompt
    contents.append(
        types.Content(
            role="user",
            parts=[types.Part.from_text(text=user_message.strip())]
        )
    )

    # Configure system prompt & generation parameters
    config = types.GenerateContentConfig(
        system_instruction=system_instruction,
        temperature=0.7,
    )

    try:
        response = client.models.generate_content(
            model=model_name,
            contents=contents,
            config=config,
        )
        if not response or not response.text:
            return "I apologize, but I couldn't generate a response. Please try rephrasing your question."
        return response.text.strip()
    except APIError as e:
        error_msg = str(e)
        if "API_KEY_INVALID" in error_msg or "invalid api key" in error_msg.lower():
            raise GeminiServiceError("The provided Gemini API key appears to be invalid. Please check your key.")
        elif "RESOURCE_EXHAUSTED" in error_msg or "quota" in error_msg.lower():
            raise GeminiServiceError("Gemini API quota exceeded or rate limit reached. Please try again shortly.")
        raise GeminiServiceError(f"Gemini API Error: {error_msg}")
    except Exception as e:
        raise GeminiServiceError(f"Unexpected error while communicating with Gemini API: {str(e)}")
